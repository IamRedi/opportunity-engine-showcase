"""Build canonical empty SQLite schema locally; apply once to a NEW remote pilot DB.

Never exports jobs.db or credentials. Existing cloud databases fail closed.
"""
import argparse
import os
from pathlib import Path
import sqlite3
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))


def schema_sql():
    import repository as repo
    import config
    with tempfile.TemporaryDirectory() as temp:
        path = Path(temp)/'empty.sqlite3'
        # Explicit path always uses the local migration path, even with cloud env configured.
        old = os.environ.get('APP_ENV')
        os.environ['APP_ENV'] = 'production'
        try:
            repo.init(path)
        finally:
            if old is None: os.environ.pop('APP_ENV',None)
            else: os.environ['APP_ENV'] = old
        con=sqlite3.connect(path)
        try:
            tables=con.execute("SELECT name,sql FROM sqlite_master WHERE type='table' AND sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid").fetchall()
            # FTS shadow tables are generated by the virtual table itself.
            statements=[sql+';' for name,sql in tables if not name.startswith('opportunities_fts_')]
            statements += [sql+';' for (sql,) in con.execute("SELECT sql FROM sqlite_master WHERE type IN ('index','trigger') AND sql IS NOT NULL ORDER BY type")]
            statements += ["CREATE TABLE login_attempts(key TEXT PRIMARY KEY, window INTEGER NOT NULL, count INTEGER NOT NULL);"]
            statements += ["INSERT INTO settings(key,value) VALUES('schema_version','%s');" % repo.SCHEMA_VERSION,
                "INSERT INTO settings(key,value) VALUES('usage_enforcement_state','disabled');",
                "INSERT INTO tenants(id,name,slug,status,branding,created_at,updated_at) VALUES(1,'Example Workspace','example-workspace','active','{}',datetime('now'),datetime('now'));",
                "INSERT INTO tenants(id,name,slug,status,branding,created_at,updated_at) VALUES(2,'Pilot Friend','pilot-friend','active','{}',datetime('now'),datetime('now'));"]
            return '\n'.join(statements)
        finally:
            con.close()


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--apply-new-database',action='store_true')
    args=parser.parse_args();sql=schema_sql()
    if not args.apply_new_database:
        print(sql);return
    import cloud_database
    con=cloud_database.connect()
    try:
        if con.execute("SELECT count(*) FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").fetchone()[0]:
            raise SystemExit('Refusing to overwrite an existing cloud database')
        con.executescript('BEGIN IMMEDIATE;\n'+sql+'\nCOMMIT;')
        print('Created empty cloud pilot schema; no local user data exported.')
    finally:
        con.close()


if __name__=='__main__':main()
